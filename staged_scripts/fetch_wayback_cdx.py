def fetch_recent_captures(url: str, days: int = 7, match_type: str = "exact",
                          collapse_digits: int = 8):
    """Captures of `url` in the last `days` days. collapse_digits=8 dedupes to one
    row per day (YYYYMMDD prefix); use a bigger number for finer granularity.
    match_type defaults to "exact" (one URL) -- "domain"/"host" are far slower and
    time out on any site with real traffic; use them only for genuinely small or
    rarely-archived domains."""
    now = datetime.now(timezone.utc)
    since = (now - timedelta(days=days)).strftime("%Y%m%d")
    params = {"url": url, "matchType": match_type, "from": since,
             "to": now.strftime("%Y%m%d"), "collapse": f"timestamp:{collapse_digits}",
             "output": "json"}
    doc = _get(f"{BASE}?{urllib.parse.urlencode(params)}")
    if not doc or len(doc) < 2:
        return  # header-only or empty response: no captures in this window
    header, rows = doc[0], doc[1:]
    fetched_at = now.isoformat()
    for row in rows:
        rec = dict(zip(header, row))
        yield {
            "source": "wayback_cdx",
            "fetched_at": fetched_at,
            "id": f"{rec.get('urlkey')}:{rec.get('timestamp')}",
            "watched_url": url,
            "original_url": rec.get("original"),
            "captured_at": rec.get("timestamp"),  # YYYYMMDDhhmmss
            "status_code": rec.get("statuscode"),
            "mimetype": rec.get("mimetype"),
            "digest": rec.get("digest"),
            "length": rec.get("length"),
        }


def fetch_watchlist(urls, days: int = 7, match_type: str = "exact"):
    """Captures for every URL in `urls`, one query per URL. A single slow/failed
    site (timeout, 403, etc.) is logged to stderr and skipped rather than aborting
    the whole run -- with hundreds of sites in one pass, one bad actor shouldn't
    cost every other site's data."""
    for url in urls:
        try:
            yield from fetch_recent_captures(url, days=days, match_type=match_type)
        except Exception as exc:  # noqa: BLE001 - keep the watchlist run going
            print(f"wayback_cdx: skipping {url!r}: {exc!r}", file=sys.stderr)


